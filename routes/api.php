    Route::get('/archive/documents/{id}/audit', [ArchiveController::class, 'audit'])->whereNumber('id');
    Route::get('/archive/documents/{id}/versions/{number}/{mode}', [ArchiveController::class, 'file'])->whereNumber('id')->whereNumber('number')->whereIn('mode', ['preview', 'download', 'print']);
    Route::get('/quality', [QualityController::class, 'index']);
    Route::get('/quality/access', [QualityController::class, 'access']);
